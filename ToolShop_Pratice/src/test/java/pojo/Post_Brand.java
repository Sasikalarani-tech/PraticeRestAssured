package pojo;

public class Post_Brand 
{
	private String name,slug;
	public Post_Brand(String name,String slug)
	{
		this.name=name;
		this.slug=slug;
	}
	public void setName()
	{
		this.name=name;
	}
	public void setSlug()
	{
		this.slug=slug;
	}
	public String getName()
	{
		return name;
	}
	public String getSlug()
	{
		return slug;
	}

}
